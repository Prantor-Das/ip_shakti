export interface SamhitaCategory {
  id: string;
  name: string;
  description: string;
  iconName: string;
  count: number;
}

export interface SourceReference {
  name: string;
  type: 'government' | 'botanical' | 'classical' | 'research' | 'patent' | 'official';
  url: string;
  accessedAt?: string;
  notes?: string;
}

export interface ResearchPaper {
  title: string;
  authors?: string;
  year?: number | string;
  journal?: string;
  url: string;
  summary: string;
}

export interface ImageMetadata {
  url: string;
  source: string;
  creator: string;
  license: string;
  attribution: string;
  sourceUrl?: string;
}

export interface SamhitaEntry {
  id: string; // samhita_id, e.g. ashwagandha-withania-somnifera
  slug: string;
  commonName: string;
  scientificName: string; // accepted botanical name
  synonyms: string[];
  regionalNames: Record<string, string>; // e.g. { hindi: 'अश्वगन्धा', tamil: 'அமுக்கரா', sanskrit: 'अश्वगन्धा' }
  category: 'HERBS' | 'MEDICINAL PLANTS' | 'FORMULATIONS' | 'CLASSICAL KNOWLEDGE' | 'TRADITIONAL KNOWLEDGE' | 'AYURVEDA HISTORY' | 'RESEARCH' | 'IP & PATENTS';
  family: string;
  partsUsed: string[];
  botanicalDescription: string;
  overview: string;
  traditionalContext: string;
  ayurvedicContext: {
    rasa?: string; // Taste
    virya?: string; // Potency
    vipaka?: string; // Post-digestive effect
    doshaEffect?: string;
    uses: string[];
  };
  classicalReferences: string[];
  relatedFormulations: string[];
  researchReferences: ResearchPaper[];
  ipInformation: {
    patentStatus: string;
    priorArtHighlights: string[];
    tkdlStatus: string;
    patentabilityNotes: string;
  };
  jurisdictions: string[];
  image: string; // display URL
  imageMetadata: ImageMetadata;
  informationSources: SourceReference[];
  relatedKnowledgeSlugs: string[];
}

